const ManagedMarker = "Generated by Odin v2"

var (
	ErrUnmanagedGeneratedConfig = errors.New("existing OpenCode config is not Odin-managed")
	ErrEditedGeneratedConfig    = errors.New("existing OpenCode config was edited by hand")
)

type ProjectScaffold struct {
	ProjectDir          string
	ConfigPath          string
	RuntimeProvider     string
	RuntimeBaseURL      string
	OpenAICompatibleURL string
	MemoryProvider      string
	MemoryHall          string
	Model               string
	Companion           string
	CompanionSource     string   // the config file that chose the companion
	Warnings            []string // config problems the user should fix; commands print them
}

type GenerateOptions struct {
	Force      bool
	WithMemory bool
	Context    int // num_ctx for the model; Odin runs it through a derived Ollama model with this context
}

type WriteResult struct {
	Path    string
	Written bool
	Updated bool
	State   ConfigState // of the file before this write
}

func ResolveProjectScaffold(cwd string) (ProjectScaffold, error) {
	global, err := config.Load(config.GlobalConfigPath())
	if err != nil {
		return ProjectScaffold{}, err
	}
	projectConfigPath := config.ProjectConfigPath(cwd)
	project, err := config.Load(projectConfigPath)
	if err != nil {
		return ProjectScaffold{}, err
	}

	// D4: the model and Ollama URL are machine-specific, so only ~/.odin/config.toml sets them.
	var warnings []string
	if project.Model.Default != "" {
		warnings = append(warnings, fmt.Sprintf("%s sets [model] default = %q, which Odin ignores: the model is machine-specific and comes from ~/.odin/config.toml. Delete that line from the project file.", displayName(cwd, projectConfigPath), project.Model.Default))
	}
	if project.Runtime.BaseURL != "" {
		warnings = append(warnings, fmt.Sprintf("%s sets [runtime] base_url, which Odin ignores: the Ollama URL is machine-specific and comes from ~/.odin/config.toml. Delete that line from the project file.", displayName(cwd, projectConfigPath)))
	}

	companionKey, companionSource := companions.Default().Key, "Odin's default"
	if global.Companion.Default != "" {
		companionKey, companionSource = global.Companion.Default, "~/.odin/config.toml"
	}
	if project.Companion.Default != "" {
		companionKey, companionSource = project.Companion.Default, displayName(cwd, projectConfigPath)
	}
	companion, known := companions.Lookup(companionKey)
	if !known {
		warnings = append(warnings, fmt.Sprintf("companion %q is not available in Odin v2; using %s. Run `odin companion list` to choose one.", companionKey, companion.Name))
	}

	baseURL := firstSet(global.Runtime.BaseURL, ollamaplugin.DefaultBaseURL)
	return ProjectScaffold{
		ProjectDir:          cwd,
		ConfigPath:          config.ProjectGeneratedOpenCodeConfigPath(cwd),
		RuntimeProvider:     firstSet(project.Runtime.Provider, global.Runtime.Provider, "ollama"),
		RuntimeBaseURL:      baseURL,
		OpenAICompatibleURL: ensureV1Endpoint(baseURL),
		MemoryProvider:      firstSet(project.Memory.Provider, global.Memory.Provider, "none"), // memory is opt-in
		MemoryHall:          firstSet(project.Memory.Hall, mempalaceplugin.DeriveHall(cwd)),
		Model:               firstSet(global.Model.Default, models.DefaultAgentModel),
		Companion:           companion.Key,
		CompanionSource:     companionSource,
		Warnings:            warnings,
	}, nil
}

func firstSet(values ...string) string {
	for _, value := range values {
		if value != "" {
			return value
		}
	}
	return ""
}

func displayName(cwd, path string) string {
	if rel, err := filepath.Rel(cwd, path); err == nil {
		return filepath.ToSlash(rel)
	}
	return path
}

func (s ProjectScaffold) Supported() bool {
	return strings.EqualFold(s.RuntimeProvider, "ollama")
}

// ContextModel is the derived Ollama model that runs s.Model with numCtx tokens of context.
func (s ProjectScaffold) ContextModel(numCtx int) string {
	return ollamaplugin.ContextModelName(s.Model, numCtx)
}

func (s ProjectScaffold) ProviderModel(numCtx int) string {
	return "ollama/" + s.ContextModel(numCtx)
}

func (s ProjectScaffold) SupportsMemory() bool {
	return strings.EqualFold(s.MemoryProvider, mempalaceplugin.ExpectedProvider)
}

func (s ProjectScaffold) RenderJSONC(options GenerateOptions) (string, error) {
	sampling := models.SamplingFor(s.Model)
	payload := map[string]any{
		"$schema": "https://opencode.ai/config.json",
		"provider": map[string]any{
			"ollama": map[string]any{
				"npm":  "@ai-sdk/openai-compatible",
				"name": "Ollama (local)",
				"options": map[string]any{
					"baseURL": s.OpenAICompatibleURL,
				},
				"models": map[string]any{
					s.ContextModel(options.Context): modelEntry(s.ContextModel(options.Context), options.Context, sampling),
				},
			},
		},
		"model": s.ProviderModel(options.Context),
		// OpenCode resolves instruction paths from the project root, not from this file.
		"instructions":  []string{".odin/rules.md"},
		"default_agent": s.Companion,
		"agent":         agents(sampling),
	}

	memoryComment := `// MemPalace MCP: not included by default. Re-run "odin opencode generate --with-memory" after verifying MemPalace is installed.`
	if options.WithMemory {
		if !s.SupportsMemory() {
			return "", fmt.Errorf("memory provider %q is not supported for OpenCode MCP generation; expected %q", s.MemoryProvider, mempalaceplugin.ExpectedProvider)
		}

		payload["mcp"] = map[string]any{
			"mempalace": map[string]any{
				"type":    "local",
				"command": mempalaceplugin.MCPCommand(),
				"enabled": true,
			},
		}
		memoryComment = `// MemPalace MCP: enabled via the documented local server command "python -m mempalace.mcp_server".`
	}

	body, err := json.MarshalIndent(payload, "", "  ")
	if err != nil {
		return "", err
	}

	rest := fmt.Sprintf(`// Project-local OpenCode config scaffold for Odin.
// Regenerate with "odin opencode generate"; it refuses to overwrite hand edits without --force.
// Selected companion: %s
// Context: %d tokens via Ollama model %s (created by "odin start --exec").
// Uses OPENCODE_CONFIG=%s when launching OpenCode.
// Memory provider: %s
// Memory hall: %s
%s
%s
`, s.Companion, options.Context, s.ContextModel(options.Context), filepath.ToSlash(filepath.Join(".odin", "generated", "opencode.jsonc")), s.MemoryProvider, s.MemoryHall, memoryComment, string(body))
	return fmt.Sprintf("// %s. sha256:%s\n%s", ManagedMarker, contentHash(rest), rest), nil
}

// ConfigState says how the generated config on disk compares with what generate would write now.
type ConfigState int

const (
	ConfigMissing   ConfigState = iota
	ConfigUnmanaged             // no Odin marker: written by hand or another tool
	ConfigEdited                // Odin's marker, but the content no longer matches its hash
	ConfigOutdated              // untouched since Odin wrote it, but settings changed (or an older Odin wrote it)
	ConfigUpToDate
)

func (state ConfigState) String() string {
	return [...]string{"missing", "not generated by Odin", "edited by hand", "out of date", "up to date"}[state]
}

func contentHash(content string) string {
	sum := sha256.Sum256([]byte(content))
	return hex.EncodeToString(sum[:])
}

// classify compares existing generated content with what Odin would write now.
func classify(existing, want string) ConfigState {
	existing = strings.ReplaceAll(existing, "\r\n", "\n") // a CRLF checkout is not a hand edit
	first, rest, _ := strings.Cut(existing, "\n")
	if !strings.Contains(existing, ManagedMarker) {
		return ConfigUnmanaged
	}
	_, hash, hashed := strings.Cut(first, "sha256:")
	switch {
	case first == "// "+ManagedMarker+".":
		return ConfigOutdated // written by Odin v0.2, which recorded no hash
	case !hashed:
		return ConfigEdited // the marker moved off the first line
	case strings.TrimSpace(hash) != contentHash(rest):
		return ConfigEdited
	case existing != want:
		return ConfigOutdated
	}
	return ConfigUpToDate
}

// GeneratedConfigState reports the state of the project's generated config for these generate options.
func GeneratedConfigState(cwd string, options GenerateOptions) (ConfigState, error) {
	scaffold, err := ResolveProjectScaffold(cwd)
	if err != nil {
		return ConfigMissing, err
	}
	existing, err := os.ReadFile(scaffold.ConfigPath)
	if errors.Is(err, os.ErrNotExist) {
		return ConfigMissing, nil
	} else if err != nil {
		return ConfigMissing, err
	}
	if options.WithMemory && !scaffold.SupportsMemory() {
		options.WithMemory = false // memory was switched off since the file was generated: it is out of date
	}
	want, err := scaffold.RenderJSONC(options)
	if err != nil {
		return ConfigMissing, err
	}
	return classify(string(existing), want), nil
}

func modelEntry(name string, numCtx int, sampling *models.Sampling) map[string]any {
	output := numCtx / 4
	if sampling != nil && sampling.NoThinking {
		output = min(output, 8192) // without thinking a turn's output stays far below this; the rest is usable context
	}
	entry := map[string]any{
		"name": name,
		// Lets OpenCode compact the session before it outgrows num_ctx. OpenCode also sends output as max_tokens.
		"limit": map[string]int{"context": numCtx, "output": output},
	}
	if sampling != nil {
		entry["temperature"] = true // without it OpenCode never sends an agent's temperature to this model
	}
	if sampling != nil && sampling.NoThinking {
		entry["options"] = map[string]any{"reasoningEffort": "none"} // Ollama maps reasoning_effort "none" to think=false
		// `opencode run --variant think` (or the TUI's variant key) turns thinking back on for harder problems.
		entry["variants"] = map[string]any{"think": map[string]any{"reasoningEffort": "high"}}
	}
	return entry
}

// agents maps each companion to an OpenCode primary agent. task is denied for all of them: subagents
// would be multi-agent orchestration, and a reviewer's subagent would have full edit rights.
func agents(sampling *models.Sampling) map[string]any {
	entries := map[string]any{}
	for _, companion := range companions.Registry {
		entries[companion.Key] = AgentConfig(companion, sampling)
	}
	return entries
}

// AgentConfig is the OpenCode agent entry Odin generates for a companion.
func AgentConfig(companion companions.Companion, sampling *models.Sampling) map[string]any {
	permission := map[string]any{"task": "deny"}
	if companion.ReadOnly {
		// No shell at all: command patterns cannot keep a shell read-only (`git log --output=f`, `ls > f`,
		// `go test -exec ...` all match an allow rule). Reading goes through OpenCode's read, grep and glob
		// tools. These rules come after the project's own permissions, and OpenCode applies the last match.
		permission = map[string]any{"edit": "deny", "bash": "deny", "task": "deny", "webfetch": "deny"}
	}
	entry := map[string]any{
		"description": companion.Description,
		"mode":        "primary",
		"prompt":      companion.Prompt(),
		"permission":  permission,
	}
	if sampling != nil {
		entry["temperature"], entry["top_p"] = sampling.Temperature, sampling.TopP
	}
	return entry
}

func WriteGeneratedConfig(cwd string, options GenerateOptions) (WriteResult, error) {
	scaffold, err := ResolveProjectScaffold(cwd)
	if err != nil {
		return WriteResult{}, err
	}

	if !scaffold.Supported() {
		return WriteResult{}, fmt.Errorf("unsupported runtime provider %q; OpenCode generation currently supports Ollama only", scaffold.RuntimeProvider)
	}
	if options.Context <= 0 {
		return WriteResult{}, errors.New("generate options must set a context size")
	}

	content, err := scaffold.RenderJSONC(options)
	if err != nil {
		return WriteResult{}, err
	}

	if err := os.MkdirAll(config.ProjectGeneratedDir(cwd), 0o755); err != nil {
		return WriteResult{}, err
	}

	result := WriteResult{Path: scaffold.ConfigPath, State: ConfigMissing}
	existing, err := os.ReadFile(scaffold.ConfigPath)
	if err == nil {
		result.State = classify(string(existing), content)
		result.Updated = true
		switch {
		case result.State == ConfigUpToDate:
			return result, nil
		case result.State == ConfigUnmanaged && !options.Force:
			return result, ErrUnmanagedGeneratedConfig
		case result.State == ConfigEdited && !options.Force:
			return result, ErrEditedGeneratedConfig
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return result, err
	}

	if err := os.WriteFile(scaffold.ConfigPath, []byte(content), 0o644); err != nil {
		return result, err
	}

	result.Written = true
	return result, nil
}

func ensureV1Endpoint(baseURL string) string {
	trimmed := strings.TrimRight(baseURL, "/")
	if strings.HasSuffix(trimmed, "/v1") {
		return trimmed
	}
	return trimmed + "/v1"
}

// GeneratedConfigUses reports whether the generated config points OpenCode at providerModel.
func GeneratedConfigUses(cwd, providerModel string) bool {
	body, err := os.ReadFile(config.ProjectGeneratedOpenCodeConfigPath(cwd))
	return err == nil && strings.Contains(string(body), `"model": "`+providerModel+`"`)
}
