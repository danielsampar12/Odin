func TestStripJSONC(t *testing.T) {
	in := `// header
{
  "baseURL": "http://localhost:11434/v1", // a URL is not a comment
  "quote": "say \"// hi\"",
  /* block
     comment */ "list": [1, 2,],
}
`
	var got map[string]any
	if err := json.Unmarshal(stripJSONC([]byte(in)), &got); err != nil {
		t.Fatalf("stripJSONC output is not JSON: %v\n%s", err, stripJSONC([]byte(in)))
	}
	if got["baseURL"] != "http://localhost:11434/v1" || got["quote"] != `say "// hi"` || len(got["list"].([]any)) != 2 {
		t.Fatalf("stripJSONC changed values: %v", got)
	}
}

func TestSourcesFollowOpenCodeMergeOrder(t *testing.T) {
	home := t.TempDir()
	t.Setenv("HOME", home)
	t.Setenv("XDG_CONFIG_HOME", "")
	t.Setenv("OPENCODE_CONFIG_CONTENT", `{"permission": {}}`)
	project := t.TempDir()
	write := func(path, body string) {
		t.Helper()
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write(filepath.Join(home, ".config", "opencode", "opencode.json"), `{"model": "a/global"}`)
	write(filepath.Join(project, ".odin", "generated", "opencode.jsonc"), "// Generated by Odin v2.\n{\"model\": \"ollama/odin\", \"agent\": {}}\n")
	write(filepath.Join(project, "opencode.json"), `{"model": "a/project", "permission": {}}`)
	write(filepath.Join(project, ".opencode", "opencode.jsonc"), `{ broken`)

	sources := Sources(project)
	var names []string
	for _, source := range sources {
		names = append(names, source.Name)
	}
	want := []string{"~/.config/opencode/opencode.json", "OPENCODE_CONFIG=.odin/generated/opencode.jsonc", "opencode.json", ".opencode/opencode.jsonc", "OPENCODE_CONFIG_CONTENT"}
	if len(names) != len(want) {
		t.Fatalf("sources = %q, want %q", names, want)
	}
	for i := range want {
		if names[i] != want[i] {
			t.Fatalf("sources = %q, want %q", names, want)
		}
	}
	if !sources[1].Odin || sources[1].Model != "ollama/odin" || len(sources[1].Keys) != 2 {
		t.Fatalf("generated source = %+v", sources[1])
	}
	if sources[3].Err == nil {
		t.Fatalf("an unparseable config should report an error")
	}
	overrides := ModelOverrides(sources)
	if len(overrides) != 1 || overrides[0].Name != "opencode.json" {
		t.Fatalf("ModelOverrides = %+v, want only the project opencode.json (the global one loses to Odin's)", overrides)
	}
}
